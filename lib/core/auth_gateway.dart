/// То, что клиенту Dio нужно знать о текущей сессии.
///
/// Dio не зависит от виджетов и хранилища: он видит только этот интерфейс.
abstract interface class AuthGateway {
  /// Токен доступа для заголовка Authorization или null, если не вошли.
  String? get accessToken;

  /// Обновляет пару токенов. Параллельные вызовы делят один запрос.
  /// Бросает исключение, если обновить не удалось.
  Future<void> refreshTokens();

  /// Сессию восстановить нельзя: локально выйти и показать экран входа.
  Future<void> sessionLost();
}
